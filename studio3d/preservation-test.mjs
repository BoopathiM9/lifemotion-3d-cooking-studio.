import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {join} from 'node:path';
import {root} from './host.mjs';
const job=join(root,'output/studio3d/jobs/sandwich-2026-10-20T10-19-28-760Z-refined-cpu-v2');
const file=join(job,'final/maya-3d-complete.mp4');
const hash=async()=>createHash('sha256').update(await readFile(file)).digest('hex');
const before=await hash();
const result=spawnSync(process.execPath,['--max-old-space-size=96','--max-semi-space-size=2','studio3d/render.mjs','--full','--job='+job],{cwd:root,encoding:'utf8'});
assert.notEqual(result.status,0);assert.match(result.stderr,/Preserving existing video/);assert.equal(await hash(),before);
const report={passed:true,overwriteRefused:true,originalSHA256:before,existingVideo:file};
await writeFile(join(root,'output/studio3d/tests/preservation.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
